// Import an outside content library into a game's generator library.
//   node tools/import-content.mjs havenot settings10           validate, write gen/library/settings10.js and the report
//   node tools/import-content.mjs havenot settings10 --check   validate and report only; exit 1 on errors
// Reads games/<game>/gen/library/<name>/ : the source JSON (left untouched) and companion.json (implementation
// details and rules). editor/gen/content.js has the adapters and the validator.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const G = require(join(root, 'editor/gen/core.js'));
for (const f of G.FILES.slice(1)) require(join(root, 'editor/gen', f));

const [game = 'havenot', name = 'settings10'] = process.argv.slice(2).filter((a) => !a.startsWith('--'));
const check = process.argv.includes('--check');
const dir = join(root, 'games', game, 'gen', 'library', name);
const srcFile = readdirSync(dir).find((f) => f.endsWith('.json') && f !== 'companion.json');
const source = JSON.parse(readFileSync(join(dir, srcFile), 'utf8'));
const companion = JSON.parse(readFileSync(join(dir, 'companion.json'), 'utf8'));

const problems = G.validateContent(source, companion);
const bad = problems.filter((p) => p.level === 'bad');
const warns = problems.filter((p) => p.level === 'warn');
const counts = Object.fromEntries(['settings', 'tiles', 'rooms', 'furniture', 'interactables', 'loot', 'hazards'].map((s) => [s, (source[s] || []).length]));

let content = null;
if (!bad.length) content = G.CONTENT_ADAPTERS[companion.format](source, companion);

// ------------------------------------------------------------ the report
const L = [];
L.push('# Import report: ' + srcFile, '');
L.push('Made by `node tools/import-content.mjs ' + game + ' ' + name + '` from the source file (untouched) and `companion.json`.', '');
L.push('| Section | Records |', '| --- | --- |');
for (const [s, n] of Object.entries(counts)) L.push('| ' + s + ' | ' + n + ' |');
if (content) {
  const objs = Object.values(content.objects);
  L.push('| distinct furniture objects | ' + objs.length + ' |');
  L.push('', '## What it became', '');
  const fam = {};
  for (const o of objs) fam[o.fam] = (fam[o.fam] || 0) + 1;
  L.push('**Furniture families** (the drawing each object uses): ' + Object.entries(fam).sort((a, b) => b[1] - a[1]).map(([f, n]) => f + ' ' + n).join(', ') + '.', '');
  const styles = (kind) => {
    const c = {};
    for (const t of Object.values(content.tiles)) if (t.kind === kind) c[t.style] = (c[t.style] || 0) + 1;
    return Object.entries(c).map(([s, n]) => s + (n > 1 ? ' ×' + n : '')).join(', ');
  };
  L.push('**Floor painters:** ' + styles('floor') + '.', '', '**Wall painters:** ' + styles('wall') + '.', '', '**Light fittings:** ' + styles('light') + '.', '');
  const beh = {};
  for (const h of Object.values(content.hazards)) beh[h.behaviour] = (beh[h.behaviour] || 0) + 1;
  L.push('**Hazard behaviours:** ' + Object.entries(beh).map(([b, n]) => b + ' ' + n).join(', ') + '.', '');
  const kinds = {};
  for (const i of Object.values(content.interactables)) kinds[i.kind] = (kinds[i.kind] || 0) + 1;
  L.push('**Device kinds:** ' + Object.entries(kinds).map(([b, n]) => b + ' ' + n).join(', ') + '.', '');
  const cl = {};
  for (const r of Object.values(content.rooms)) cl[r.cluster] = (cl[r.cluster] || 0) + 1;
  L.push('**Clusters** (derived: the JSON has none; see companion.json `clusters`): ' + Object.entries(cl).sort((a, b) => b[1] - a[1]).map(([c, n]) => c + ' ' + n).join(', ') + '.', '');
  L.push('**Loot items:** ' + Object.values(content.loot).reduce((n, l) => n + l.items.length, 0) + ' satchel items from ' + counts.loot + ' loot records.', '');
}
L.push('## Problems', '');
if (!problems.length) L.push('None.');
for (const p of bad) L.push('- **Error** ' + p.section + (p.id ? ' `' + p.id + '`' : '') + ': ' + p.text);
for (const p of warns) L.push('- Warning ' + p.section + (p.id ? ' `' + p.id + '`' : '') + ': ' + p.text);
writeFileSync(join(dir, 'IMPORT-REPORT.md'), L.join('\n') + '\n');

console.log(srcFile + ': ' + Object.entries(counts).map(([s, n]) => s + ' ' + n).join(', '));
console.log(bad.length + ' errors, ' + warns.length + ' warnings (IMPORT-REPORT.md).');
for (const p of bad.slice(0, 20)) console.log('  ERROR ' + p.section + ' ' + p.id + ': ' + p.text);
if (bad.length) process.exit(1);
if (!check) {
  const out = join(root, 'games', game, 'gen', 'library', name + '.js');
  const text = '/* HaveNot generator library — ' + name + '.js\n * GENERATED by `node tools/import-content.mjs ' + game + ' ' + name + '` from ' + name + '/' + srcFile + ' and ' + name + '/companion.json.\n * Edit those and run it again; don\'t edit this file. The source library\'s ids are kept as they are.\n */\nLM.genLibrary(' + JSON.stringify(game) + ', { content: { ' + JSON.stringify(name) + ': ' + JSON.stringify(content) + ' } });\n';
  writeFileSync(out, text);
  console.log('Wrote ' + out.replace(root, '').replace(/\\/g, '/') + ' (' + Math.round(text.length / 1024) + ' KB).');
}
